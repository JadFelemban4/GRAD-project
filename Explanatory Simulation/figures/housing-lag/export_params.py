"""Export what the housing-lag figure draws, from the project's own code.

The figure (build.mjs beside this file) never types a physical number. It reads
params.json, which this script writes from three places in the parent repo:

  plant.predict          the engine point: gas temperature and flow at the
                         lab's thermal experiment (ThermalLab.tsx `initial`)
  thermal.ThermalParams  the turbine node's constants (c_turb is ASSUMED)
  thermal.ThermalNetwork a reference run of the turbine node, integrated the
                         way /api/thermal integrates it (0.1 s steps)

Run it from anywhere:

    python "Explanatory Simulation/figures/housing-lag/export_params.py"

tests/test_housing_figure.py recomputes everything here and fails when the
plant moves, the way test_catalog.py pins the plant's figures; then re-run this
script and rebuild the figure (`npm run figures`).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LAB = HERE.parents[1]
REPO = LAB.parent
sys.path[:0] = [str(REPO)]

import fingerprint  # noqa: E402
import thermal  # noqa: E402
from plant import charge_temperature, predict  # noqa: E402

# The lab's thermal experiment point, ThermalLab.tsx `initial`. The test checks
# that the two still agree, so the figure and the lab's charts show one engine.
POINT = {"rpm": 3000.0, "map_kpa": 180.0, "ambient_c": 42.0, "spark": 8.0, "lam": 0.92}

# The reference run: a cold start, the burner on for HEAT_S, then off for COOL_S.
# "Off" is what /api/thermal's cooling phase feeds the network: no fuel, no
# exhaust flow, gas at ambient, 800 rpm.
HEAT_S = 120
COOL_S = 180
DT = 0.1
OFF_RPM = 800.0


def engine_point():
    t_amb = POINT["ambient_c"] + 273.15
    out = predict(POINT["rpm"], POINT["map_kpa"], charge_temperature(t_amb), t_amb,
                  POINT["spark"], POINT["lam"])
    return {
        "egt_c": float(out["egt_c"]),
        "mdot_air_gps": float(out["mdot_air_gps"]),
        "mdot_fuel_gps": float(out["mdot_fuel_gps"]),
        "mdot_exh_gps": float(out["mdot_air_gps"] + out["mdot_fuel_gps"]),
    }


def reference_run(engine):
    """t_turb in K once a second, from the project's ThermalNetwork itself."""
    t_amb = POINT["ambient_c"] + 273.15
    net = thermal.ThermalNetwork()
    net.reset(t_amb=t_amb, warm=False)
    on = (engine["mdot_fuel_gps"], engine["mdot_exh_gps"], engine["egt_c"] + 273.15, POINT["rpm"])
    off = (0.0, 0.0, t_amb, OFF_RPM)
    samples = [float(net.t_turb)]
    for second in range(HEAT_S + COOL_S):
        fuel, exhaust, egt_k, rpm = on if second < HEAT_S else off
        for _ in range(int(round(1 / DT))):
            net.step(DT, fuel, exhaust, egt_k, t_amb, 0.0, 1.0, 1.0, rpm=rpm)
        samples.append(float(net.t_turb))
    return samples


def export():
    p = thermal.ThermalParams()
    engine = engine_point()
    return {
        "_about": ("Generated by export_params.py from plant.py and thermal.py. "
                   "Do not edit by hand; re-run the script."),
        "point": POINT,
        "engine": engine,
        "turbine": {
            "c_turb": float(p.c_turb),
            "ua_turb_amb": float(p.ua_turb_amb),
            "ua_gas_turb": float(p.ua_gas_turb),
            "mdot_floor_gps": 0.5,
            "dt_sub_max": float(thermal.DT_SUB_MAX),
            "evidence": {"c_turb": "ASSUMED", "ua_turb_amb": "ASSUMED", "ua_gas_turb": "ASSUMED"},
        },
        "reference": {
            "heat_s": HEAT_S,
            "cool_s": COOL_S,
            "dt": DT,
            "off_rpm": OFF_RPM,
            "t_turb_k": reference_run(engine),
        },
        "provenance": {
            "plant_sha": fingerprint._sha_files(fingerprint.PLANT_FILES),
            "derived_sha": fingerprint.derived_sha(),
            "python": f"{sys.version_info.major}.{sys.version_info.minor}",
        },
    }


def main():
    data = export()
    path = HERE / "params.json"
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(data, handle, indent=1, ensure_ascii=False)
        handle.write("\n")
    t = data["turbine"]
    tau = t["c_turb"] / (t["ua_gas_turb"] * data["engine"]["mdot_exh_gps"] + t["ua_turb_amb"])
    print(f"wrote {path.name}: gas {data['engine']['egt_c']:.2f} C at "
          f"{data['engine']['mdot_exh_gps']:.3f} g/s, tau on {tau:.2f} s, "
          f"plant_sha {data['provenance']['plant_sha']} (Python {data['provenance']['python']})")


if __name__ == "__main__":
    main()
