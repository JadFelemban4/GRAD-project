"""check_x2_convergence.py -- had the X2 agents settled? C4's rule, at X2's budget.

    python check_x2_convergence.py --selftest     the practice set regenerates; no seed overlap
    python check_x2_convergence.py                X2: results/x2_convergence.txt (about 30 min)
    python check_x2_convergence.py --dry-run      the code path on X1's seeds 0-4 at 30k/40k/50k
                                                  steps: context, never X2's verdict

Written 11 October 2026 with results/PREREGISTRATION_X2.md, BEFORE any X2 agent
trained; the rule is that file's section 5c, which is C4's (PREREGISTRATION_C4.md
5b, set by the team on 23 September) moved to X2's budget and units:

  measured   every agent at three points in the last third of its training --
             the checkpoints at 720 000 and 900 000 steps and final.zip at
             1 080 000 -- on the same ten PRACTICE episodes, deterministic
             policy, weights pinned. With the ruler fixed, a change between
             checkpoints is a change in the agent.
  settled    the agent's practice cut (100 x (1 - median damage / the baseline
             ECU's damage on the same climb)) moves by no more than 2.715 points,
             half the MEI, across the three points.
  pair       the seed's d = sighted cut - blinded cut moves by no more than
  settled    2.715 points across the same three points.
  converged  at least 4 of the 5 agents in EACH arm settled, AND at least 4 of
             the 5 pairs settled: one dissenter each, as C4's 7 of 8 allowed one.

THE PRACTICE SET IS NOT THE TEST SET. The locked climb, as scored, under ten
preference-weight draws made once from numpy.default_rng(20261011) the way
reset() draws them, with episode seeds 4000-4009, which no frozen test set uses
(--selftest checks both). C4 judged on its own design's roads with draws its
test never used; this does the same on X2's scored road. Judging on
evaluate.EPISODES would be looking at the test before the test.

What the verdict does and cannot do: it labels the result (section 6 of the
preregistration). It does not select a checkpoint, extend a run or drop one.
"""
import argparse
import os
from multiprocessing import Pool

import numpy as np

import fingerprint as FP
from analyse_x1 import MEI_PTS

HERE = os.path.dirname(os.path.abspath(__file__))

SETTLE_BAND = MEI_PTS / 2              # 2.715 points of cut
CHECKPOINTS = (720_000, 900_000, 1_080_000)
X2_STEPS = 1_080_000
MIN_SETTLED = 4                        # of 5, in EACH arm
MIN_PAIRS_SETTLED = 4                  # of 5 seed pairs
SEEDS = range(5)
OWN = "runs/wideair_dt1"

PRACTICE_SEED = 20261011
# (episode seed, (w_track, w_fuel, w_life)) -- regenerated by practice_set()
PRACTICE = (
    (4000, (0.556287, 0.024118, 0.419595)),
    (4001, (0.631445, 0.170314, 0.198242)),
    (4002, (0.684343, 0.18521, 0.130447)),
    (4003, (0.611132, 0.031315, 0.357553)),
    (4004, (0.669548, 0.247697, 0.082755)),
    (4005, (0.630175, 0.129604, 0.240221)),
    (4006, (0.516226, 0.144023, 0.339751)),
    (4007, (0.618863, 0.020387, 0.36075)),
    (4008, (0.479373, 0.205003, 0.315624)),
    (4009, (0.689537, 0.108087, 0.202377)),
)


def practice_set(seed=PRACTICE_SEED, n=10):
    """Regenerate PRACTICE: weights as SupervisoryTunerEnv.reset() draws them."""
    from engine_env import TRACK_W_MIN, TRACK_W_MAX
    rng = np.random.default_rng(seed)
    out = []
    for i in range(n):
        w_track = float(TRACK_W_MIN + (TRACK_W_MAX - TRACK_W_MIN) * rng.random())
        w_rest = rng.dirichlet(np.ones(2)) * (1.0 - w_track)
        out.append((4000 + i, (round(w_track, 6), round(float(w_rest[0]), 6), round(float(w_rest[1]), 6))))
    return tuple(out)


def checkpoint_path(agent_dir, steps, final_steps):
    if steps == final_steps:
        return os.path.join(agent_dir, "final.zip")
    return os.path.join(agent_dir, f"ckpt_{steps}_steps.zip")


def baseline_damage():
    """The baseline ECU on the locked climb: it ignores the weights, so one episode."""
    import check_premise as C
    import engines
    import evaluate as E
    s, w = PRACTICE[0]
    return float(E.run_episode(C.p_neutral, s, w, True, plant=engines.get("b58"))["damage"])


def score(job):
    tag, path, key = job
    os.environ.setdefault("OMP_NUM_THREADS", "1")
    import engines
    import evaluate as E
    from stable_baselines3 import SAC
    pol = E.agent_policy(SAC.load(path, device="cpu"))
    preview = not tag.startswith("blind")
    dmg = [E.run_episode(pol, s, w, preview, plant=engines.get("b58"))["damage"] for s, w in PRACTICE]
    return tag, key, float(np.median(dmg)), FP.model_budget(path)


def selftest():
    import evaluate
    ok_set = practice_set() == PRACTICE
    overlap = {s for s, _ in PRACTICE} & ({e[0] for e in evaluate.EPISODES} | {e[0] for e in evaluate.EPISODES_D2})
    print(f"PRACTICE regenerates from seed {PRACTICE_SEED}      : {ok_set}")
    print(f"no episode seed shared with a frozen test set : {not overlap}")
    print(f"settle band = half the MEI ({MEI_PTS}/2)          : {SETTLE_BAND == MEI_PTS / 2}")
    ok = ok_set and not overlap
    print("SELF-TEST " + ("PASSES" if ok else "FAILS"))
    return 0 if ok else 1


def verdict(runs, checkpoints, final_steps, seeds, label):
    base = baseline_damage()
    tags = [f"{arm}_seed{s}" for s in seeds for arm in ("sighted", "blind")]
    jobs = [(t, checkpoint_path(os.path.join(HERE, runs, t), k, final_steps), k)
            for t in tags for k in checkpoints]
    missing = [j[1] for j in jobs if not os.path.isfile(j[1])]
    if missing:
        raise SystemExit("missing checkpoints:\n  " + "\n  ".join(missing))
    n = max(1, min(10, (os.cpu_count() or 4) - 2))
    with Pool(n) as pool:
        out = pool.map(score, jobs)
    cut = {(t, k): 100.0 * (1.0 - d / base) for t, k, d, _ in out}
    lines = [f"X2 CONVERGENCE -- {label}",
             f"rule: results/PREREGISTRATION_X2.md 5c; band {SETTLE_BAND:.3f} points of cut; practice set of "
             f"{len(PRACTICE)} episodes on the locked climb; baseline ECU damage there {base:.1f}",
             "", "agent           " + "".join(f"{k:>12,}" for k in checkpoints) + "    moves   settled"]
    settled = {}
    for t in tags:
        c = [cut[(t, k)] for k in checkpoints]
        mv = max(c) - min(c)
        settled[t] = mv <= SETTLE_BAND
        lines.append(f"{t:<16}" + "".join(f"{x:>12.2f}" for x in c) + f"   {mv:6.2f}   {'yes' if settled[t] else 'NO'}")
    lines += ["", "pair (sighted - blinded)"]
    pairs = {}
    for s in seeds:
        d = [cut[(f"sighted_seed{s}", k)] - cut[(f"blind_seed{s}", k)] for k in checkpoints]
        mv = max(d) - min(d)
        pairs[s] = mv <= SETTLE_BAND
        lines.append(f"  seed {s:<10}" + "".join(f"{x:>+12.2f}" for x in d) + f"   {mv:6.2f}   {'yes' if pairs[s] else 'NO'}")
    n_s = sum(settled[t] for t in tags if t.startswith("sighted"))
    n_b = sum(settled[t] for t in tags if t.startswith("blind"))
    n_p = sum(pairs.values())
    k = len(seeds)
    need_arm = MIN_SETTLED if k == 5 else k - 1
    need_pair = MIN_PAIRS_SETTLED if k == 5 else k - 1
    conv = n_s >= need_arm and n_b >= need_arm and n_p >= need_pair
    lines += ["", f"settled: sighted {n_s} of {k}, blinded {n_b} of {k} (need {need_arm} each); "
              f"pairs {n_p} of {k} (need {need_pair})",
              f"VERDICT: {'CONVERGED' if conv else 'NOT-CONVERGED'}"]
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--dry-run", action="store_true",
                    help="the code path on X1's seeds 0-4 at 30k/40k/50k steps (context only)")
    a = ap.parse_args()
    if a.selftest:
        raise SystemExit(selftest())
    if a.dry_run:
        lines = verdict("runs/extremes_dt1", (30_000, 40_000, 50_000), 50_000, range(5),
                        "DRY RUN on X1's seeds 0-4 at 30k/40k/50k steps: context, NOT X2's verdict")
        out = "results/x2_convergence_dryrun.txt"
    else:
        lines = verdict(OWN, CHECKPOINTS, X2_STEPS, SEEDS, OWN)
        out = "results/x2_convergence.txt"
    print("\n".join(lines))
    with open(os.path.join(HERE, out), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"\nwritten to {out}")


if __name__ == "__main__":
    main()
